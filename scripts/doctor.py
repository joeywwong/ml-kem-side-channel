"""Read-only environment probe; never opens a scope, flashes or resets a target."""
import ctypes
from datetime import datetime, timezone
import importlib.metadata
import json
import os
import platform
import shutil
import subprocess
from common import ROOT,save


def probe(cmd):
    try:
        p=subprocess.run(cmd,capture_output=True,timeout=12)
        raw=p.stdout+p.stderr
        encoding='utf-16le' if b'\0' in raw[:80] else 'utf-8'
        return {'exit_code':p.returncode,'output':raw.decode(encoding,errors='replace').strip()[:2500]}
    except (OSError,subprocess.TimeoutExpired) as e:
        return {'status':'NOT RUN','reason':str(e)}


def main():
    tools={}
    for name,args in {'git':['--version'],'gcc':['--version'],'clang':['--version'],
        'make':['--version'],'cmake':['--version'],'arm-none-eabi-gcc':['--version'],
        'openocd':['--version'],'STM32_Programmer_CLI':['--version']}.items():
        tools[name]=probe([name,*args]) if shutil.which(name) else {'status':'NOT RUN','reason':'not on PATH'}
    packages={}
    for name in ['numpy','matplotlib','pytest','chipwhisperer','pyusb']:
        try: packages[name]=importlib.metadata.version(name)
        except importlib.metadata.PackageNotFoundError: packages[name]='NOT INSTALLED'
    cpu=platform.processor()
    memory='UNKNOWN'
    if os.name=='nt':
        import winreg
        with winreg.OpenKey(winreg.HKEY_LOCAL_MACHINE,r'HARDWARE\DESCRIPTION\System\CentralProcessor\0') as key:
            cpu=winreg.QueryValueEx(key,'ProcessorNameString')[0]
        class Memory(ctypes.Structure):
            _fields_=[('length',ctypes.c_uint32),('load',ctypes.c_uint32)]+[(k,ctypes.c_uint64) for k in ['total','avail','page_total','page_avail','virt_total','virt_avail','extended']]
        m=Memory();m.length=ctypes.sizeof(m)
        if ctypes.windll.kernel32.GlobalMemoryStatusEx(ctypes.byref(m)): memory=m.total
        # Report only aggregate USB classes/VID-PID; never serials/instance IDs.
        usb=probe(['powershell','-NoProfile','-Command',
            "$ErrorActionPreference='Stop'; Get-PnpDevice -PresentOnly | Where-Object { $_.InstanceId -like 'USB*' } | ForEach-Object { if ($_.InstanceId -match 'VID_[0-9A-F]{4}&PID_[0-9A-F]{4}') { $Matches[0] } } | Sort-Object -Unique"])
    else:
        usb=probe(['lsusb']) if shutil.which('lsusb') else {'status':'NOT RUN','reason':'lsusb unavailable'}
        try: memory=os.sysconf('SC_PAGE_SIZE')*os.sysconf('SC_PHYS_PAGES')
        except (ValueError,OSError): pass
    result={'status':'PASS','timestamp_utc':datetime.now(timezone.utc).isoformat(),
        'os':platform.platform(),'cpu':cpu,'logical_cpus':os.cpu_count(),'physical_memory_bytes':memory,
        'python':platform.python_version(),'tools':tools,'packages':packages,'usb_enumeration':usb,
        'wsl':probe(['wsl','--list','--quiet']) if shutil.which('wsl') else {'status':'NOT RUN'},
        'hardware':{'nano':'NOT RUN (NO HARDWARE), user states not available',
                    'stm32f407':'NOT RUN: no on-device authorization or identification',
                    'board_revision':'UNKNOWN','verified_flash':'UNKNOWN','verified_ram':'UNKNOWN'}}
    save('environment.json',result)
    lines=['# Environment preflight','', 'Generated by `python scripts/doctor.py`. PASS means the probe ran; it does not mean hardware is available.', '',
        '```json',json.dumps(result,indent=2),'```','',
        'No board was opened, reset, flashed, or measured. Windows device enumeration is independent of WSL USB visibility.',
        'Nano F030 nominal budget: 16 KB flash / 4 KB RAM (user specification, physical revision unverified).',
        'F407 exact part, physical marking, flash-size register and usable RAM/linker map remain UNKNOWN. Device ID 0x413 alone is insufficient.',
        'Local host paths, serial numbers and private document names are omitted from public metadata.']
    supplementary=ROOT/'results/wsl-environment.json'
    if supplementary.exists():
        lines += ['', '## Supplementary WSL probe', '',
                  'An authorized probe outside the restricted Windows sandbox reached Ubuntu. The initial access-denied result above is scoped to that sandbox, not absence of WSL. No WSL USB passthrough is inferred.',
                  '', '```json',supplementary.read_text().strip(),'```', '',
                  'ASan and UBSan execution results: `results/sanitizers-linux.json`; Windows runtime diagnostics: `results/sanitizers-windows.json`.']
    (ROOT/'docs/ENVIRONMENT.md').write_text('\n'.join(lines)+'\n',encoding='utf-8')
    print(json.dumps(result,indent=2))


if __name__=='__main__': main()
